from ultralytics import YOLO

if __name__ == '__main__':

    # โหลดโมเดล (แนะนำให้เริ่มจาก Pre-trained model เพื่อความแม่นยำ)
    model = YOLO('yolo26s.pt')    # รุ่น s ใหญ่กว่า n ตีกรอบแม่นกว่า (mAP50-95 0.56 -> 0.61)

    # เริ่มเทรนพร้อมตั้งค่า Data Augmentation เพื่อแก้ปัญหาภาพมุมเดียว
    results = model.train(
        data='dataset_sam/data.yaml',   # กรอบที่ปรับด้วย SAM (01b-refine_labels_sam.py) ทำให้ mAP50-95 0.728 -> 0.869
        epochs=200,
        patience=60,         # หยุดเองถ้า 60 epochs ติดกันไม่ดีขึ้น
        imgsz=640,
        batch=16,
        cos_lr=True,         # ค่อยๆ ลด learning rate แบบ cosine ช่วยให้ loss นิ่งช่วงท้าย
        optimizer="MuSGD",
        device=0,

        # --- พารามิเตอร์สำหรับ Data Augmentation หลัก ---
        degrees=5.0,         # สุ่มหมุนภาพ -5 ถึง +5 องศา (หมุนมากไปกรอบตรงจะพองใหญ่กว่าซองจริง สอนให้ตีกรอบหลวม)
        shear=0.0,           # ปิดการบิดภาพเฉียง ด้วยเหตุผลเดียวกับ degrees
        perspective=0.0005,  # เพิ่มความลึก (จำลองจากมุมที่ต่างออกไป)

        # --- การพลิกภาพ (Flip) ---
        fliplr=0.5,          # โอกาส 50% ที่จะพลิกภาพซ้าย-ขวา
        flipud=0.0,          # พลิกภาพบน-ล่าง (แนะนำให้ตั้งเป็น 0.0 เว้นแต่วัตถุของคุณในสภาพแวดล้อมจริงสามารถกลับด้านได้)

        # --- พารามิเตอร์ขั้นสูงที่แนะนำให้เปิดไว้ ---
        mosaic=1.0,          # (ค่าเริ่มต้น) นำภาพ 4 ภาพมาตัดแปรรวมกัน ช่วยให้โมเดลตรวจจับวัตถุขนาดเล็กได้ดีขึ้น
        mixup=0.1,           # ซ้อนภาพ 2 ภาพเข้าด้วยกันแบบโปร่งแสง ช่วยลด Overfitting ได้ดีมาก

        # ปิด Mosaic ในช่วง N epochs สุดท้ายเพื่อให้โมเดลปรับกับภาพจริง
        close_mosaic=20
    )